import {
  chart,
  chartInk,
  colors,
  font,
  motion,
  radius,
  rootFontSize,
  shadow,
  simpleModeScale,
  space,
  type,
} from './tokens';
import type { Theme } from './tokens';

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
}

/** px to rem against the 16 px root, trimmed so 13 px is `0.8125rem` and 16 px is `1rem`. */
export function rem(px: number): string {
  const value = Math.round((px / rootFontSize) * 10000) / 10000;
  return `${value}rem`;
}

/** Colour custom properties for one theme, in the mockup's `--name` form. */
export function themeVariables(theme: Theme): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, value] of Object.entries(colors[theme])) out[`--${kebab(name)}`] = value;
  chart.forEach((c, i) => {
    out[`--chart-${i + 1}`] = c;
  });
  out['--chart-ink'] = chartInk;
  return out;
}

/**
 * Theme-independent properties: radii, fonts, the type scale and spacing in rem, shadows and motion.
 * Names avoid Tailwind's `--text-*`, `--spacing-*` and `--shadow-*` namespaces so `@theme` can map
 * onto them without a self-reference.
 */
export function scaleVariables(): Record<string, string> {
  const out: Record<string, string> = {};
  out['--radius'] = `${radius.md}px`;
  out['--radius-sm'] = `${radius.sm}px`;
  out['--radius-lg'] = `${radius.lg}px`;
  out['--radius-pill'] = `${radius.pill}px`;
  out['--font-sans'] = font.sans;
  out['--font-mono'] = font.mono;
  for (const [name, t] of Object.entries(type)) {
    out[`--font-size-${kebab(name)}`] = rem(t.size);
    out[`--line-height-${kebab(name)}`] = rem(t.lineHeight);
    out[`--font-weight-${kebab(name)}`] = String(t.weight);
  }
  for (const [step, px] of Object.entries(space)) out[`--space-${step}`] = rem(px);
  out['--elevation-low'] = shadow.low;
  out['--elevation-art'] = shadow.art;
  out['--duration-fast'] = `${motion.fast}ms`;
  out['--duration-normal'] = `${motion.normal}ms`;
  out['--duration-slow'] = `${motion.slow}ms`;
  out['--easing-standard'] = motion.easing;
  return out;
}

function block(selector: string, vars: Record<string, string>): string {
  const lines = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`);
  return `${selector} {\n${lines.join('\n')}\n}`;
}

function indent(text: string): string {
  return text
    .split('\n')
    .map((l) => `  ${l}`)
    .join('\n');
}

/**
 * The stylesheet `tokens.css` is generated from (then formatted with prettier by the build script).
 * Dark by default, light by attribute or preference; simple mode scales the root; reduced motion
 * turns animation off everywhere (DESIGN.md rule 12).
 */
export function tokensCss(): string {
  const light = themeVariables('light');
  return [
    block(':root', { ...themeVariables('dark'), ...scaleVariables() }),
    block(':root[data-theme="light"]', light),
    `@media (prefers-color-scheme: light) {\n${indent(block(':root:not([data-theme="dark"])', light))}\n}`,
    block(':root[data-mode="simple"]', { 'font-size': `${simpleModeScale * 100}%` }),
    `@media (prefers-reduced-motion: reduce) {\n${indent(
      block('*, *::before, *::after', {
        'animation-duration': '0.01ms !important',
        'animation-iteration-count': '1 !important',
        'transition-duration': '0.01ms !important',
        'scroll-behavior': 'auto !important',
      }),
    )}\n}`,
  ].join('\n\n');
}

